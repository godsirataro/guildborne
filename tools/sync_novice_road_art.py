"""Share reviewed Crown Road geometry with the optional Atomic runtime course."""
import argparse
from pathlib import Path

REPLACEMENTS = (
    ("-- Chapter 00 walkable environment prototype. No quest or combat receipts.",
     "-- Generated from review/NoviceRoadKit.luau; optional course art, no reward authority."),
    ('SetAttribute("ReviewOnly",true)', 'SetAttribute("CoursePrototype",true)'),
    ("Enum.ModelStreamingMode.Persistent -- Keep the small review board visible to the gallery camera.",
     "Enum.ModelStreamingMode.Atomic"),
)


def runtime_source(source: str) -> bytes:
    """Fail closed if the review factory's integration contract has changed."""
    source = source.replace("\r\n", "\n")
    for old, new in REPLACEMENTS:
        if source.count(old) != 1:
            raise ValueError(f"Expected exactly one integration anchor: {old!r}")
        source = source.replace(old, new, 1)
    return source.encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check exact generated bytes without writing")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "src/server/Services/NoviceRoadArt.luau"
    try:
        expected = runtime_source((root / "review/NoviceRoadKit.luau").read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        parser.exit(1, f"NOVICE_ROAD_ART generation failed: {error}\n")
    if args.check:
        if not target.is_file() or target.read_bytes() != expected:
            parser.exit(1, "NOVICE_ROAD_ART out of sync; run tools/sync_novice_road_art.py\n")
        print("NOVICE_ROAD_ART exact LF bytes verified; runtime mode Atomic")
    else:
        target.write_bytes(expected)
        print("NOVICE_ROAD_ART synchronized; quest observations belong to NoviceCourseWorld")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
