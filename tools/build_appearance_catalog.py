"""Generate the runtime ID specification from the reviewed original kit manifests.

No meshes are generated and no asset is promoted to imported/available.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "production/character-kit-v1/original/Guildborne_Character_Pipeline_v1/manifest"
OUTPUT = ROOT / "src/shared/Data/AppearanceCatalog.luau"


def lua(value):
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (str, int, float)):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, list):
        return "{" + ",".join(lua(item) for item in value) + "}"
    return "{" + ",".join("[" + lua(key) + "]=" + lua(item) for key, item in value.items() if item is not None) + "}"


def render():
    assets = json.loads((MANIFEST / "asset_registry.json").read_text(encoding="utf-8"))["assets"]
    bodies = json.loads((MANIFEST / "body_presets.json").read_text(encoding="utf-8"))["presets"]
    skins = json.loads((MANIFEST / "skin_palettes.json").read_text(encoding="utf-8"))["palettes"]
    assert len(assets) == 89 and len({a["asset_id"] for a in assets}) == 89
    assert len(bodies) == 13 and len(skins) == 20
    aliases = json.loads((ROOT / "production/character-kit-v1/aliases.json").read_text(encoding="utf-8"))
    catalog = {"Version": 1, "Status": "PLANNED_SPECIFICATION_NOT_GENERATED_ASSETS", "Assets": {}, "Bodies": {}, "SkinPalettes": {}, "HeadAliases": aliases,
               "Races": {r: True for r in ("HUMAN", "ELF", "ORC", "DWARF")},
               "HairColors": {"HAIR_DARK_BROWN": "#3C271D", "HAIR_BLACK": "#211C1B", "HAIR_BROWN": "#6A4030", "HAIR_BLOND": "#D3B780", "HAIR_WHITE": "#D9D6CA", "HAIR_RED": "#9B4E2D"},
               "SlotOrder": ["INNER_TOP", "INNER_BOTTOM", "OUTER_TOP", "OUTER_BOTTOM", "CHEST_ARMOR", "SHOULDERS", "GLOVES", "BOOTS", "BELT", "CAPE", "HEADWEAR", "HAIR", "BEARD", "RACE_FEATURE"],
               "Defaults": {"HUMAN": "HUMAN_STANDARD", "ELF": "ELF_GRACEFUL", "ORC": "ORC_STANDARD", "DWARF": "DWARF_COMPACT"}}
    for asset in assets:
        assert asset["roblox_asset_id"] is None and asset["status"] == "PLANNED"
        catalog["Assets"][asset["asset_id"]] = {"id": asset["asset_id"], "category": asset["category"], "raceId": asset["race"], "slot": asset["slot"], "fitProfile": asset["fit_profile"], "technology": asset["technology"], "sourcePath": asset["source_path"], "exportPath": asset["export_path"], "studioPath": asset["studio_path"], "status": asset["status"], "runtimeImported": False}
    for body in bodies:
        entry = dict(body)
        entry["assetId"] = "CHR_BDY_" + body["bodyPresetId"] + "_V01"
        assert entry["assetId"] in catalog["Assets"]
        catalog["Bodies"][body["bodyPresetId"]] = entry
    for skin in skins:
        catalog["SkinPalettes"][skin["skinPaletteId"]] = skin
    assert all(value in catalog["Assets"] for value in aliases.values())
    lines = ["--!strict", "-- GENERATED by tools/build_appearance_catalog.py from original reviewed manifests.", "-- PLANNED IDs only. No Roblox IDs, generated meshes, or tested fit is implied.", "local Catalog: any = {"]
    for key, value in catalog.items():
        if isinstance(value, dict) and key in ("Assets", "Bodies", "SkinPalettes"):
            lines.append("\t" + key + " = {")
            lines.extend("\t\t[" + lua(k) + "] = " + lua(v) + "," for k, v in value.items())
            lines.append("\t},")
        else:
            lines.append("\t" + key + " = " + lua(value) + ",")
    lines.extend(["}", "local function freeze(value: any)", "\tfor _, child in pairs(value) do if type(child) == \"table\" then freeze(child) end end", "\ttable.freeze(value)", "end", "freeze(Catalog)", "return Catalog", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        assert OUTPUT.read_text(encoding="utf-8") == expected, "AppearanceCatalog differs from original manifests"
        print("PASS: original 89 assets, 13 bodies, 20 palettes and aliases match runtime specification")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print("Generated planned ID specification:", OUTPUT)
